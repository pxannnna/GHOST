"""Build assets/building/rooms.json from the PDF trace + on-site measurements.

    python -m services.acoustics.build_rooms

rooms.json is the single file both the room matcher and the 3D model read.
Every value says where it came from (`*_source`: traced / estimated / measured).
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path
from typing import Any, Dict, List, Optional

from shared.config import ROOT
from services.acoustics.rooms import polygon_area

BUILDING = ROOT / "assets" / "building"


def _scale(trace: Dict[str, Any], meas: Dict[str, Any]) -> tuple[float, str]:
    ref = meas.get("scale_reference") or {}
    if ref.get("length_m") and ref.get("length_pt"):
        return float(ref["length_m"]) / float(ref["length_pt"]), \
            f"measured: {ref.get('description', ref.get('room_id'))}"
    if ref.get("room_id") and ref.get("length_m") and ref.get("width_m"):
        # Tape-measured rectangular room: long side <-> long side, short <-> short, averaged.
        poly = next(r["polygon_pt"] for r in trace["rooms"] if r["room_id"] == ref["room_id"])
        xs, ys = [p[0] for p in poly], [p[1] for p in poly]
        a, b = max(xs) - min(xs), max(ys) - min(ys)
        L_pt, W_pt = max(a, b), min(a, b)
        L_m, W_m = max(ref["length_m"], ref["width_m"]), min(ref["length_m"], ref["width_m"])
        return (L_m / L_pt + W_m / W_pt) / 2, \
            f"measured: {ref['room_id']} taped {L_m} x {W_m} m"
    return float(trace["default_scale_m_per_pt"]), "estimated from seat counts"


def build(trace: Dict[str, Any], meas: Dict[str, Any]) -> Dict[str, Any]:
    s, scale_source = _scale(trace, meas)
    ox, oy = trace["origin_pt"]
    out_rooms: List[Dict[str, Any]] = []
    for r in trace["rooms"]:
        m = (meas.get("rooms") or {}).get(r["room_id"], {}) or {}
        # PDF y points down; flip so +y is "up the page" in metres.
        poly = [[round((x - ox) * s, 3), round((oy - y) * s, 3)] for x, y in r["polygon_pt"]]

        h: Optional[float] = m.get("ceiling_height_m")
        lo, hi = m.get("ceiling_min_m"), m.get("ceiling_max_m")
        if h is None and lo is not None and hi is not None:
            h = (lo + hi) / 2
        if h is not None:
            ceiling_source = (f"estimated (same as {m['estimated_from']})" if m.get("estimated_from")
                              else "measured")
            rng = [lo if lo is not None else h, hi if hi is not None else h]
        else:
            ceiling_source = "assumed"
            h = r.get("ceiling_height_m", 3.0)
            rng = r.get("ceiling_height_range_m", [h, h])

        room = {
            "room_id": r["room_id"],
            "floor_id": r["floor_ids"][0],
            "floor_ids": r["floor_ids"],
            "label": m.get("label") or r["label"],
            "kind": r["kind"],
            "polygon_m": poly,
            "ceiling_height_m": h,
            "ceiling_height_range_m": rng,
            "ceiling_source": ceiling_source,
            "outline_source": "traced (approximate outline)" if r.get("approximate_outline") else "traced",
            "area_m2": round(polygon_area(poly), 1),
            "approximate": ceiling_source != "measured" or bool(r.get("approximate_outline"))
                           or scale_source.startswith("estimated"),
        }
        for k in ("seats", "accessible", "note", "label_unverified"):
            if k in r:
                room[k] = r[k]
        if m.get("length_m") and m.get("width_m"):
            room["tape_measured_dims_m"] = {"length": m["length_m"], "width": m["width_m"]}
        out_rooms.append(room)

    return {
        "_comment": "GENERATED by `python -m services.acoustics.build_rooms` - edit trace_nucleus.json / measurements.json instead.",
        "building_id": "nucleus",
        "source": trace["source"],
        "scale_m_per_pt": round(s, 5),
        "scale_source": scale_source,
        "scope": "enclosed rooms only (no corridors, atrium, café, open study zones, plant, staff rooms)",
        "floors_excluded": ["LG"],
        "rooms": out_rooms,
    }


def main(argv: Optional[List[str]] = None) -> None:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--trace", type=Path, default=BUILDING / "trace_nucleus.json")
    ap.add_argument("--measurements", type=Path, default=BUILDING / "measurements.json")
    ap.add_argument("--out", type=Path, default=BUILDING / "rooms.json")
    a = ap.parse_args(argv)
    meas = json.loads(a.measurements.read_text()) if a.measurements.exists() else {}
    data = build(json.loads(a.trace.read_text()), meas)
    a.out.write_text(json.dumps(data, indent=1) + "\n")
    print(f"wrote {a.out.relative_to(ROOT)}  scale={data['scale_m_per_pt']} m/pt ({data['scale_source']})")
    for r in data["rooms"]:
        print(f"  {r['room_id']:20s} floors {','.join(r['floor_ids']):4s} {r['area_m2']:7.1f} m2  "
              f"h={r['ceiling_height_m']:.2f} m ({r['ceiling_source']})  {r['label']}")


if __name__ == "__main__":
    main()
